    def test_grid_parser_and_pdf_keep_three_weeks_of_dated_exams(self):
        times = [
            '07:00-08:00', '08:00-08:30', '08:30-09:30', '09:30-10:00',
            '10:00-11:00', '11:00-11:30', '11:30-12:30', '12:30-13:00',
            '13:00-14:00', '14:00-14:30', '14:30-15:30', '15:30-16:00',
            '16:00-17:00', '17:00-17:30', '17:30-18:30',
        ]
        rows = [
            ['THREE-WEEK TEST TIMETABLE'],
            [None, 'BAE (65)'],
            [None, *times],
        ]
        first_day = date(2026, 1, 5)
        for offset in range(21):
            day = first_day + timedelta(days=offset)
            exam = f'AEU {offset + 1:05d} Advanced Examination Paper'
            exam_row = [f'{day:%A %d/%m/%Y}', exam, *(['---'] * (len(times) - 1))]
            venue_row = [None, 'Main Examination Hall', *([None] * (len(times) - 1))]
            rows.extend((exam_row, venue_row))
        timetable = extract_exam_timetable(make_exam_workbook([('Sheet1', rows)]), 'BAE')
        self.assertEqual(len(timetable.days), 21)
        self.assertEqual(timetable.days[0].label, 'Monday 05/01/2026')
        self.assertEqual(timetable.days[-1].label, 'Sunday 25/01/2026')
        self.assertEqual(timetable.days[-1].cells[0].course, 'AEU 00021 Advanced Examination Paper')
        pdf = build_exam_grid_pdf(timetable, 'test1', 1)
        self.assertTrue(pdf.startswith(b'%PDF-'))
        self.assertIn(b'/MediaBox [ 0 0 841.8898 595.2756 ]', pdf)
        self.assertGreaterEqual(len(re.findall(rb'/Type\s*/Page\b', pdf)), 2)

